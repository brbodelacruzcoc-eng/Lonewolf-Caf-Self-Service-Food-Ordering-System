    private void markError(javax.swing.JComponent field, javax.swing.border.Border normalBorder, boolean hasError) {
        field.setBorder(hasError
                ? BorderFactory.createLineBorder(ERROR_RED, 2)
                : normalBorder);
    }

    private void clearBorderOnTyping(javax.swing.text.JTextComponent field, javax.swing.border.Border normalBorder) {
        field.getDocument().addDocumentListener(new javax.swing.event.DocumentListener() {
            public void insertUpdate(javax.swing.event.DocumentEvent e) { markError(field, normalBorder, false); }
            public void removeUpdate(javax.swing.event.DocumentEvent e) { markError(field, normalBorder, false); }
            public void changedUpdate(javax.swing.event.DocumentEvent e) { markError(field, normalBorder, false); }
        });
    }

