    private void loginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginActionPerformed
    String uN = username.getText().trim();
    String pW = new String(password.getPassword());

    markError(username, defaultUserBorder, false);
    markError(password, defaultPassBorder, false);

    // ---------- USERNAME CHECKS ----------
    if (uN.isEmpty()) {
        markError(username, defaultUserBorder, true);
        JOptionPane.showMessageDialog(this,
            "Please enter your username.",
            "Username Error",
            JOptionPane.ERROR_MESSAGE);
        username.requestFocus();
        return;
    }
    if (uN.length() < 6) {
        markError(username, defaultUserBorder, true);
        JOptionPane.showMessageDialog(this,
            "Username is too short.\nIt must be at least 6 characters (you typed " + uN.length() + ").",
            "Username Error",
            JOptionPane.ERROR_MESSAGE);
        username.requestFocus();
        return;
    }
    if (uN.contains(" ")) {
        markError(username, defaultUserBorder, true);
        JOptionPane.showMessageDialog(this,
            "Username must not contain spaces.",
            "Username Error",
            JOptionPane.ERROR_MESSAGE);
        username.requestFocus();
        return;
    }

    // ---------- PASSWORD CHECKS ----------
    if (pW.isEmpty()) {
        markError(password, defaultPassBorder, true);
        JOptionPane.showMessageDialog(this,
            "Please enter your password.",
            "Password Error",
            JOptionPane.ERROR_MESSAGE);
        password.requestFocus();
        return;
    }
    if (pW.length() < 6) {
        markError(password, defaultPassBorder, true);
        JOptionPane.showMessageDialog(this,
            "Password is too short.\nIt must be at least 6 characters (you typed " + pW.length() + ").",
            "Password Error",
            JOptionPane.ERROR_MESSAGE);
        password.requestFocus();
        return;
    }

    Connection conn = DBConnection.connect();

    try {
        String sql = "SELECT * FROM tbl_users WHERE uname = ? AND password = ?";
        PreparedStatement pst = conn.prepareStatement(sql);

        pst.setString(1, uN);
        pst.setString(2, pW);

        ResultSet rs = pst.executeQuery();

        if (rs.next()) {

            // Get user information from database
            int userId = rs.getInt("id");
            String role = rs.getString("role");

            // Save logged-in user
            UserSession.setUser(userId, uN);

            JOptionPane.showMessageDialog(this, "Login successful!");

            // Check the user's role
            if (role.equalsIgnoreCase("Owner")) {

                // OWNER / manager
                transaction transactionForm = new transaction();
                transactionForm.setVisible(true);
                this.dispose();

            } else if (role.equalsIgnoreCase("Cashier")|| role.equalsIgnoreCase("Barista")) {

                // CASHIER
                cashierdashboard cashierdashboardForm = new cashierdashboard();
                cashierdashboardForm.setVisible(true);
                this.dispose();

            } else {

                // Unknown role
                JOptionPane.showMessageDialog(
                    this,
                    "Your account has no valid role.",
                    "Login Error",
                    JOptionPane.ERROR_MESSAGE
                );
            }

        } else {

            JOptionPane.showMessageDialog(
                this,
                "Invalid username or password",
                "Error",
                JOptionPane.ERROR_MESSAGE
            );
        }

        rs.close();
        pst.close();
        conn.close();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Database Error: " + e.getMessage(),
            "Error",
            JOptionPane.ERROR_MESSAGE
        );
    }  // TODO add your handling code here:
    }//GEN-LAST:event_loginActionPerformed

