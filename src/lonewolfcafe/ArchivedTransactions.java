    private void loadArchive() {

    DefaultTableModel model =
            (DefaultTableModel) tblArchive.getModel();

    model.setRowCount(0);

    String sql = "SELECT archive_id, order_id, user_id, order_date, "
        + "total_amount, status, order_type, payment_method, "
        + "archived_date "
        + "FROM tbl_archived_orders "
        + "ORDER BY archived_date DESC";

    try (Connection conn = DBConnection.connect();
         PreparedStatement pst = conn.prepareStatement(sql);
         ResultSet rs = pst.executeQuery()) {

        while (rs.next()) {

            model.addRow(new Object[]{
                rs.getInt("archive_id"),
                rs.getInt("order_id"),
                rs.getInt("user_id"),
                rs.getTimestamp("order_date"),
                rs.getBigDecimal("total_amount"),
                rs.getString("status"),
                rs.getString("order_type"),
                rs.getString("payment_method"),
                rs.getTimestamp("archived_date")
            });
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error loading archive: " + e.getMessage()
        );
    }
}
    private void searchArchive() {
    String searchText = txtSearch.getText().trim();

    if (searchText.isEmpty()) {
        sorter.setRowFilter(null);
    } else {
        sorter.setRowFilter(
                RowFilter.regexFilter(
                        "(?i)" + Pattern.quote(searchText)
                )
        );
    }
}

