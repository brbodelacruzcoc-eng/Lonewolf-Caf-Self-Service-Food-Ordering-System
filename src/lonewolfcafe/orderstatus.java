private void setupList(JList<String> list, DefaultListModel<String> listModel,
                       Color color, int fontSize, int cellWidth) {
    list.setModel(listModel);
    list.setFont(new Font("Georgia", Font.BOLD, fontSize));
    list.setFixedCellHeight(fontSize + 30);
    list.setFixedCellWidth(cellWidth);
    list.setLayoutOrientation(JList.HORIZONTAL_WRAP);  // grid, not one long column
    list.setVisibleRowCount(-1);
    list.setSelectionModel(new javax.swing.DefaultListSelectionModel() {
        @Override public void setSelectionInterval(int a, int b) { } // not clickable
    });
    list.setCellRenderer(new DefaultListCellRenderer() {
        @Override
        public Component getListCellRendererComponent(JList<?> l, Object value,
                int index, boolean sel, boolean focus) {
            JLabel lbl = (JLabel) super.getListCellRendererComponent(
                    l, value, index, false, false);
            lbl.setHorizontalAlignment(SwingConstants.CENTER);
            lbl.setForeground(color.darker());
            return lbl;
        }
    });
}

private void loadBoard() {
    queuedModel.clear();
    preparingModel.clear();
    readyModel.clear();

    // PAID & QUEUED: paid orders still waiting for the barista
    String queuedSql =
        "SELECT order_id FROM tbl_orders " +
        "WHERE status = 'Pending' " +
        "AND (user_id IS NOT NULL " +
        "     OR LOWER(COALESCE(payment_method, 'cash')) <> 'cash') " +
        "ORDER BY order_date ASC";

    // PREPARING: orders the barista has started
    String preparingSql =
        "SELECT order_id FROM tbl_orders " +
        "WHERE status = 'Preparing' " +
        "ORDER BY order_date ASC";

    // READY: today's 8 most recent completed orders
    String readySql =
        "SELECT order_id FROM tbl_orders " +
        "WHERE status = 'Completed' AND DATE(order_date) = CURDATE() " +
        "ORDER BY order_id DESC LIMIT 8";

    try (Connection con = DBConnection.connect()) {
        fillModel(con, queuedSql, queuedModel, 10);
        fillModel(con, preparingSql, preparingModel, 10);
        fillModel(con, readySql, readyModel, 8);
    } catch (SQLException e) {
        logger.log(java.util.logging.Level.WARNING, "Board refresh failed", e);
    }
}

// fills a list with order numbers, and adds "+N more" if there are extras
private void fillModel(Connection con, String sql,
                       DefaultListModel<String> listModel, int max) throws SQLException {
    int total = 0;
    try (PreparedStatement pst = con.prepareStatement(sql);
         ResultSet rs = pst.executeQuery()) {
        while (rs.next()) {
            total++;
            if (total <= max) {
                listModel.addElement("#" + rs.getInt("order_id"));
            }
        }
    }
    if (total > max) {
        listModel.addElement("+" + (total - max) + " more");
    }
}
